//! Native syscall handlers.
//!
//! Mirrors `procedures/` in spirit: a registry of handlers keyed by
//! `(arch_name, syscall_num)` that short-circuits the Python
//! `_handle_syscall_callback` round-trip.
//!
//! # Scope
//!
//! This is not a two-syscall fast path — it is the bulk of the kernel
//! surface the engine executes without ever entering Python. The registry
//! holds one `register_syscalls!` table per dispatch key: `AMD64`, `X86`,
//! `ARM`, `ARM64`, `MIPS32`, `MIPS64`, and `CGC`. Per-arch Linux ABIs assign
//! different numbers to the same syscall, so the tables are deliberately not
//! merged; the same handler type is simply registered under each arch's
//! number. `NativeSyscallRegistry::new` is the authoritative list; do not
//! copy counts out of it into prose.
//!
//! Coverage spans process exit (`exit`, `exit_group`), IO (`read`,
//! `write`, `readv`/`writev`), the file namespace (`open`/`openat`/`close`,
//! `stat`/`lstat`/`fstat`/`newfstatat`, `access`, `readlink`, and the
//! `directory` family), memory (`brk`, `mmap`, `mprotect`, `munmap`,
//! `arch_prctl`), concurrency primitives (`futex`, `epoll_*`, `eventfd*`),
//! identity, resource limits, time, signals, process startup, and the CGC
//! syscalls. Handlers come in three flavors: full implementations that
//! mutate `RustSimState`, zero-arg constant returners generated by
//! `identity::constant_syscall!`, and `stub_syscall!`-generated ones that
//! mint a fresh symbolic return value (matching Python's
//! `procedures/stubs/syscall_stub.py::syscall`). The per-file module
//! docs are authoritative for each family's divergences from the Python
//! `SimProcedure` it mirrors; `docs/extending-angr/native_coverage_matrix.rst`
//! tracks the deliberate gaps.
//!
//! # Dispatch
//!
//! `exploration::core_outcome_handlers::handle_syscall_core` picks the
//! dispatch key (`"CGC"` when the project's OS is cgc, otherwise
//! `state.arch().name()`), looks the number up via
//! `NativeSyscallRegistry::get`, and on a hit extracts the handler's
//! declared arg count. A handler that returns `Ok(SyscallOutcome)` means
//! no `PendingCallback` is created: `Continue` / `ContinueSymbolic` write
//! the return value to the return register and execution proceeds, `Exit`
//! routes the state to `STASH_DEADENDED`. Any `Err(SyscallError)` — or a
//! failure to extract the args — bounces to the Python implementation,
//! which stays authoritative, so an unsupported case degrades in
//! behavior-preserving fashion rather than producing a wrong answer.
//!
//! # Layout
//!
//! This file is the registration manifest: `NativeSyscallRegistry`, the
//! `register_syscalls!` macro that spells its rows, and `new`'s
//! per-arch tables. The shared vocabulary those handlers are written
//! against — `SyscallError`, `SyscallOutcome`, the `NativeSyscall` trait,
//! the arg-extraction / bounding / fresh-symbolic helpers and the
//! `stub_syscall!` / `require_syscall_args!` macros — lives in the sibling
//! `support` module (angr-5mnx3.58) and is re-exported here, so every
//! `crate::syscalls::X` / `use super::X;` in a handler file still resolves.
//!
//! Architecture note (amd64 syscall ABI):
//! * args: rdi, rsi, rdx, r10, r8, r9
//! * return: rax
//! * The dispatcher uses `extract_syscall_args` (true syscall ABI), so
//!   handlers see `r10` at index 3, not `rcx`. This matters for any
//!   handler with ≥4 args (e.g. rt_sigaction). Other arches go through
//!   the same call, which reads each arch's syscall-ABI register list
//!   from the calling convention, so handlers are written against
//!   argument *indices* and never name registers directly.

